def get_word_frequency(clean_word: str) -> float:
    """Returns the lexical frequency score of a word in [0.05, 1.0].

    High scores (0.80 - 1.0) indicate high-frequency sight-words.
    Low scores (<= 0.20) indicate rare, specialized, or technical terms.
    """
    if not clean_word:
        return 0.5

    # 1. Exact match in unified frequency lexicon
    if clean_word in UNIFIED_FREQUENCY_LEXICON:
        return UNIFIED_FREQUENCY_LEXICON[clean_word]

    # Check variation without ZWNJ
    if ZWNJ in clean_word:
        alt = clean_word.replace(ZWNJ, "")
        if alt in UNIFIED_FREQUENCY_LEXICON:
            return UNIFIED_FREQUENCY_LEXICON[alt]

    # 2. Verb lemma resolution: present / continuous / negative forms
    # Matches patterns like می‌خوانم, میخوانم, نمی‌روند, نمیروند, etc.
    verb_m = VERB_PRESENT_REGEX.match(clean_word)
    if verb_m:
        stem = verb_m.group(1).replace(ZWNJ, "")
        lemma = PRESENT_STEM_TO_LEMMA.get(stem)
        if lemma and lemma in UNIFIED_FREQUENCY_LEXICON:
            return max(0.20, UNIFIED_FREQUENCY_LEXICON[lemma] - 0.05)
        if stem in UNIFIED_FREQUENCY_LEXICON:
            return max(0.20, UNIFIED_FREQUENCY_LEXICON[stem] - 0.05)

    # 3. Past participle (ماضی نقلی / صفت مفعولی) lemma resolution
    # Matches patterns like گفته‌ام, گفتهام, رفته‌اند, رفتهاند, etc.
    past_part_m = PAST_PARTICIPLE_REGEX.match(clean_word)
    if past_part_m:
        past_stem = past_part_m.group(1).replace(ZWNJ, "")
        if past_stem in UNIFIED_FREQUENCY_LEXICON:
            return max(0.20, UNIFIED_FREQUENCY_LEXICON[past_stem] - 0.05)

    # 4. Past tense verb inflection (خواندم -> خواند)
    past_verb_m = PAST_VERB_REGEX.match(clean_word)
    if past_verb_m:
        p_stem = past_verb_m.group(1).replace(ZWNJ, "")
        if len(p_stem) >= 3 and p_stem in UNIFIED_FREQUENCY_LEXICON:
            return max(0.20, UNIFIED_FREQUENCY_LEXICON[p_stem] - 0.05)

    # 5. Noun plural and pronominal clitic resolution
    # Matches patterns like کتاب‌ها, کتابها, خانواده‌ام, خانوادهام, etc.
    noun_m = NOUN_AFFIX_REGEX.match(clean_word)
    if noun_m:
        noun_base = noun_m.group(1).replace(ZWNJ, "")
        if noun_base in UNIFIED_FREQUENCY_LEXICON:
            return max(0.20, UNIFIED_FREQUENCY_LEXICON[noun_base] - 0.05)

    # 6. Compound decomposition: if all parts of a ZWNJ compound are known common words
    if ZWNJ in clean_word:
        parts = clean_word.split(ZWNJ)
        if all(p in UNIFIED_FREQUENCY_LEXICON for p in parts):
            avg_freq = sum(UNIFIED_FREQUENCY_LEXICON[p] for p in parts) / len(parts)
            return max(0.40, avg_freq - 0.10)

    # 7. Generic affix strip with minimum-stem guard (P3-18)
    affix_m = AFFIX_STRIP_REGEX.match(clean_word)
    if affix_m:
        stem = affix_m.group(1).replace(ZWNJ, "")
        # Minimum stem length: guard against over-stripping 1-letter suffixes (م/ی) from short stems
        if len(stem) >= 3 and stem in UNIFIED_FREQUENCY_LEXICON:
            return max(0.20, UNIFIED_FREQUENCY_LEXICON[stem] - 0.05)

    # 8. Digits / formatted numbers
    if any(c.isdigit() for c in clean_word):
        return 0.40

    # 9. Unknown / rare Persian word baseline
    return 0.05
